CREATE TABLE issued_documents (
  issued_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  document_request_id integer NOT NULL,
  document_no varchar(30) NOT NULL UNIQUE,
  verification_token uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  issued_at timestamptz NOT NULL DEFAULT now(),
  valid_until date NOT NULL,
  status issued_documents_status NOT NULL DEFAULT 'valid',
  signed_by_official_id integer NOT NULL,
  content_snapshot jsonb NOT NULL,
  content_hash char(64) NOT NULL,
  file_url text,
  print_count smallint NOT NULL DEFAULT 0,
  revoked_at timestamptz,
  revoked_by integer,
  revoke_reason text,
  PRIMARY KEY (issued_id),
  CONSTRAINT chk_issued_documents_1 CHECK (valid_until >= (issued_at AT TIME ZONE 'UTC')::date),
  CONSTRAINT chk_issued_documents_2 CHECK (print_count >= 0),
  CONSTRAINT chk_issued_documents_3 CHECK (content_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT chk_issued_documents_4 CHECK (status <> 'revoked' OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL AND revoke_reason IS NOT NULL))
