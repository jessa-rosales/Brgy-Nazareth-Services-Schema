-- ===== Users_and_Roles =====
CREATE TABLE roles (
  role_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  role_name varchar(50) NOT NULL UNIQUE,
  description text,
  web_access boolean NOT NULL DEFAULT false,
  mobile_access boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (role_id)
);
CREATE TABLE modules (
  module_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  module_code varchar(40) NOT NULL UNIQUE,
  module_name varchar(80) NOT NULL UNIQUE,
  PRIMARY KEY (module_id)
);
CREATE TABLE role_module_access (
  role_id integer NOT NULL,
  module_id integer NOT NULL,
  access_level role_module_access_access_level NOT NULL,
  PRIMARY KEY (role_id, module_id)
);
CREATE TABLE users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  person_id integer NOT NULL UNIQUE,
  role_id integer NOT NULL,
  username citext NOT NULL UNIQUE,
  email citext NOT NULL UNIQUE,
  password_hash text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  must_change_password boolean NOT NULL DEFAULT true,
  failed_login_count smallint NOT NULL DEFAULT 0,
  locked_until timestamptz,
  last_login_at timestamptz,
