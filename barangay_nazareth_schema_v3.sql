CREATE TABLE civil_statuses (
  civil_status_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  status_name varchar(60) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true,
  PRIMARY KEY (civil_status_id)
);
CREATE TABLE persons (
  person_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  first_name varchar(80) NOT NULL,
  middle_name varchar(80),
  last_name varchar(80) NOT NULL,
  suffix varchar(10),
  sex persons_sex,
  civil_status_id integer,
  birth_date date,
  birth_place varchar(120),
  citizenship varchar(50) DEFAULT 'Filipino',
  religion varchar(60),
