CREATE TABLE official_positions (
  position_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  position_name varchar(80) NOT NULL UNIQUE,
  rank_order smallint NOT NULL DEFAULT 99,
  can_sign_documents boolean NOT NULL DEFAULT false,
  PRIMARY KEY (position_id)
);
CREATE TABLE officials (
  official_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  person_id integer NOT NULL,
  position_id integer NOT NULL,
  committee varchar(100),
  term_start date NOT NULL,
  term_end date,
  signature_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (official_id),
  UNIQUE (person_id, position_id, term_start),
  CONSTRAINT chk_officials_1 CHECK (term_end IS NULL OR term_end >= term_start)
