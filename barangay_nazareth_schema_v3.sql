-- At most 3 current collectors per team.
CREATE OR REPLACE FUNCTION chk_team_max_collectors() RETURNS trigger AS $$
BEGIN
  IF NEW.crew_role = 'collector' AND NEW.removed_at IS NULL AND
     (SELECT count(*) FROM collection_team_members
       WHERE team_id = NEW.team_id AND crew_role = 'collector' AND removed_at IS NULL
         AND team_member_id <> COALESCE(NEW.team_member_id, -1)) >= 3 THEN
    RAISE EXCEPTION 'A team can have at most 3 current collectors.';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_team_max_collectors BEFORE INSERT OR UPDATE ON collection_team_members
  FOR EACH ROW EXECUTE FUNCTION chk_team_max_collectors();

-- A team can only use an Active truck.
CREATE OR REPLACE FUNCTION chk_team_vehicle_active() RETURNS trigger AS $$
BEGIN
  IF NEW.archived_at IS NULL AND
     (SELECT status FROM vehicles WHERE vehicle_id = NEW.vehicle_id) <> 'active' THEN
    RAISE EXCEPTION 'The selected truck is not Active.';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_team_vehicle_active BEFORE INSERT OR UPDATE ON collection_teams
  FOR EACH ROW EXECUTE FUNCTION chk_team_vehicle_active();

-- completed_at must be filled exactly when the referral status is 'Completed'
-- (this was a CHECK before status became an editable lookup table).
CREATE OR REPLACE FUNCTION chk_referral_completed() RETURNS trigger AS $$
DECLARE s text;
BEGIN
  SELECT status_name INTO s FROM referral_statuses WHERE referral_status_id = NEW.referral_status_id;
  IF (lower(s) = 'completed') <> (NEW.completed_at IS NOT NULL) THEN
    RAISE EXCEPTION 'completed_at must be filled only when the referral status is Completed.';
  END IF;
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_referral_completed BEFORE INSERT OR UPDATE ON report_referrals
  FOR EACH ROW EXECUTE FUNCTION chk_referral_completed();

